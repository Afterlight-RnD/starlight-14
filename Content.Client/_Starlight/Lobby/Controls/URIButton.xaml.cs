using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Starlight.Lobby.Controls;

[GenerateTypedNameReferences]
public sealed partial class URIButton : Button
{
    [Dependency] private readonly IUriOpener _uriOpener = default!;

    private bool _visibleWithoutURI = true;

    public bool VisibleWithoutURI
    {
        get => _visibleWithoutURI;
        set
        {
            if (value == _visibleWithoutURI)
                return;
            if (!VisibleWithoutURI && _uri == null)
                Visible = false;
        }
    }

    private string? _uri = null;

    public string? URI
    {
        get => _uri;
        set
        {
            if (value == _uri)
                return;
            if (value == null && !VisibleWithoutURI)
                Visible = false;
        }
    }

    public URIButton()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        OnPressed += HandlePressed;
        Visible = URI != null;
    }

    private void HandlePressed(ButtonEventArgs obj)
    {
        if (URI == null)
            return;
        _uriOpener.OpenUri(URI);
    }
}