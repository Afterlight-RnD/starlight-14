using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Starlight.Lobby.Controls;

[GenerateTypedNameReferences]
public sealed partial class URIButton : Button
{
    [Dependency] private readonly IUriOpener _uriOpener = default!;

    private bool _hideWhenInvalid = true;

    public bool HideWhenInvalid
    {
        get => _hideWhenInvalid;
        set
        {
            if (value == _hideWhenInvalid)
                return;
            if (HideWhenInvalid)
                Visible = true;
            Visible = !HideWhenInvalid && _uri != null;
        }
    }

    private string? _uri = null;

    public string? URI
    {
        get => _uri;
        set
        {
            if (value == _uri)
                return;
            if (HideWhenInvalid)
                Visible = _uri != null;
        }
    }

    public URIButton()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        OnPressed += HandlePressed;
        Visible = !HideWhenInvalid && _uri != null;
    }

    private void HandlePressed(ButtonEventArgs obj)
    {
        if (URI == null)
            return;
        _uriOpener.OpenUri(URI);
    }
}