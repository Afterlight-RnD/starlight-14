using Content.Client._Starlight.CharacterEditor.Systems;
using Content.Client._Starlight.UI;
using Content.Client._Starlight.UI.Core;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Starlight.Lobby;

[GenerateTypedNameReferences]
public sealed partial class SLDummyLobbyControl : SLControl
{
    public SLDummyLobbyControl()
    {
        RobustXamlLoader.Load(this);
        LayoutContainer.SetAnchorPreset(Background, LayoutContainer.LayoutPreset.Wide);
        LayoutContainer.SetAnchorPreset(this, LayoutContainer.LayoutPreset.Wide);
    }

    protected override void EnteredTree()
    {
        SubscribeUIEvent<EnterCharacterEditorUIEvent>(HandleEnterCharacterEditor);
        SubscribeUIEvent<ExitCharacterEditorUIEvent>(HandleExitCharacterEditor);
        SubscribeUIEvent<LobbyBackgroundChangedUIEvent>(OnLobbyBackgroundChanged);
    }

    private void OnLobbyBackgroundChanged(ref readonly LobbyBackgroundChangedUIEvent args)
    {
        Background.Texture = args.BackgroundTexture;
    }

    private void HandleExitCharacterEditor(ref readonly ExitCharacterEditorUIEvent args)
    {
        CharacterEditor.Visible = false;
        Lobby.Visible = true;
    }

    private void HandleEnterCharacterEditor(ref readonly EnterCharacterEditorUIEvent args)
    {
        Lobby.Visible = false;
        CharacterEditor.Visible = true;
    }
}