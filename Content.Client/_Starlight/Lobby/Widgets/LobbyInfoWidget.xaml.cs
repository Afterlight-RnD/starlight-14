using Content.Client.GameTicking.Managers;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._Starlight.Lobby.Widgets;

[GenerateTypedNameReferences]
public sealed partial class LobbyInfoWidget : UIWidget
{
    [Dependency] private readonly IGameTiming _gameTiming = default!;
    private ClientGameTicker _gameTicker = default!;
    public LobbyInfoWidget()
    {
        RobustXamlLoader.Load(this);
        _gameTicker = EntityManager.System<ClientGameTicker>();
    }

    protected override void EnteredTree()
    {
        _gameTicker.InfoBlobUpdated += UpdateInfo;
    }

    protected override void ExitedTree()
    {
        _gameTicker.InfoBlobUpdated -= UpdateInfo;
    }

    private void UpdateInfo()
    {
        var text = _gameTicker.ServerInfoBlob;
        if (text == null)
        {
            ServerInfoText.Text = null;
            return;
        }
        ServerInfoText.SetMessage(FormattedMessage.FromMarkupOrThrow(text));
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        if (_gameTicker.IsGameStarted)
        {
            var roundTime = _gameTiming.CurTime.Subtract(_gameTicker.RoundStartTimeSpan);
            StationTime.Text = Loc.GetString("lobby-state-player-status-round-time", ("hours", roundTime.Hours), ("minutes", roundTime.Minutes));
            return;
        }
        StationTime.Text = Loc.GetString("lobby-state-player-status-round-not-started");
    }
}