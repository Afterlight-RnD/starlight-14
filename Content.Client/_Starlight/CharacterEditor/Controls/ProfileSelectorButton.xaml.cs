using Content.Client._Starlight.CharacterEditor.Systems;
using Content.Client._Starlight.CharacterProfiles;
using Content.Client._Starlight.UI.Systems.CharacterView.Controls;
using Content.Shared._Starlight.CharacterProfileSystem.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.UIEvents;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Starlight.CharacterEditor.Controls;

[GenerateTypedNameReferences]
public sealed partial class ProfileSelectorButton : ContainerButton, IUIEventSubscriber
{
    public int Slot { get; private set; } = -1;
    public bool HasProfile { get; private set; }

    public ProfileSelectorButton()
    {
        RobustXamlLoader.Load(this);
        EnabledCheck.OnToggled += OnEnabledToggle;
    }

    private void OnEnabledToggle(ButtonToggledEventArgs args)
    {
        if (Slot <= 0)
            return;
        if (args.Pressed)
        {
            UserInterfaceManager.RaiseGlobalUIEvent(new CharacterProfileEnabledUIEvent(Slot));
        }

    }

    protected override void EnteredTree()
    {
        Slot = GetPositionInParent();
        UserInterfaceManager.SubscribeGlobalUIEvent<CharacterProfileUpdatedUIEvent>(this, OnCharacterSlotUpdated);
        Refresh();
    }

    protected override void ExitedTree()
    {
        UserInterfaceManager.UnSubscribeAllUIEvents(this);
    }

    private void OnCharacterSlotUpdated(CharacterProfileUpdatedUIEvent ev)
    {
        if (Slot != ev.CharacterProfile.Comp.Slot)
            return;
        UpdateCharacterProfile(ev.CharacterProfile);
    }

    public void Refresh()
    {
        UserInterfaceManager.RaiseUIEvent(this, new RefreshProfilePreviewUIEvent());
    }

    public void UpdateCharacterProfile(Entity<CharacterProfileComponent>? profile)
    {
        if (profile == null)
        {
            CharacterName.Text = "Urist McPlaceholder";
            CharacterJob.Text = "PlaceholderJob";
            CharacterView.SetEntity(null);
            Visible = false;
            HasProfile = false;
            return;
        }
        CharacterView.SetEntity(profile.Value.Comp.PreviewEntity);
        CharacterName.Text = profile.Value.Comp.Data.Profile?.Name;
        HasProfile = true;
        Visible = true;
        Disabled = false;
    }
}