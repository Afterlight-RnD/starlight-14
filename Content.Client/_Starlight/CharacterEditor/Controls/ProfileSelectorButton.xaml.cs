namespace Content.Client._Starlight.CharacterEditor.Controls;

[GenerateTypedNameReferences]
public sealed partial class ProfileSelectorButton : ContainerButton, IUIEventSubscriber
{
    public int Slot { get => CharacterView.Slot; set => CharacterView.Slot = value; }

    public ProfileSelectorButton()
    {
        RobustXamlLoader.Load(this);
        AddStyleClass(StyleClassButton);
        SetupButtonOutlines();
    }

    public void ToggleAllowDelete(bool newAllow)
    {
        DeleteButtonOutline.Visible = newAllow;
        DeleteButton.Disabled = !newAllow;
    }

    public void SetFromProfile(Entity<CharacterProfileComponent>? profile, JobPrototype? jobProto)
    {
        if (profile == null)
        {
            CharacterName.Text = "Urist McPlaceholder";
            CharacterJob.Text = "PlaceholderJob";
            Visible = false;
            Slot = -1;
            return;
        }
        CharacterName.Text = profile.Value.Comp.Data.Profile.Name;
        Slot = profile.Value.Comp.Slot;
        CharacterJob.Text = jobProto?.Name;
        Visible = true;
    }

    //TODO: redo this, this is skrungly
    private void SetupButtonOutlines()
    {
        if (EnabledCheckOutline.PanelOverride is  StyleBoxTexture enabledStyleBox)
        {
            enabledStyleBox.Texture = Theme.ResolveTexture("/Textures/Interface/Nano/slider_outline.svg.96dpi.png");
            enabledStyleBox.SetPatchMargin(StyleBox.Margin.All, 12);
            enabledStyleBox.SetContentMarginOverride(StyleBox.Margin.All, 0);
            enabledStyleBox.SetExpandMargin(StyleBox.Margin.All, 1);
            enabledStyleBox.TextureScale = new Vector2(1.1f);
            enabledStyleBox.Modulate = StyleNano.PanelDark;
        }
        if (DeleteButtonOutline.PanelOverride is StyleBoxTexture deleteStyleBox)
        {
            deleteStyleBox.Texture = Theme.ResolveTexture("/Textures/Interface/Nano/slider_outline.svg.96dpi.png");
            deleteStyleBox.SetPatchMargin(StyleBox.Margin.All, 12);
            deleteStyleBox.SetContentMarginOverride(StyleBox.Margin.All, 0);
            deleteStyleBox.SetExpandMargin(StyleBox.Margin.All, 1);
            deleteStyleBox.TextureScale = new Vector2(1.1f);
            deleteStyleBox.Modulate = StyleNano.PanelDark;
        }
    }
}