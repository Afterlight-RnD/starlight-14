using Content.Client._Starlight.CharacterEditor.Controls;
using Content.Client._Starlight.CharacterEditor.Systems;
using Content.Client._Starlight.CharacterProfiles;
using Content.Shared._Starlight.CharacterProfileSystem.Components;
using Content.Shared.CCVar;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;

namespace Content.Client._Starlight.CharacterEditor.Widgets;

[GenerateTypedNameReferences]
public sealed partial class CharacterSlotSelectorWidget : UIWidget
{
    [Dependency] private readonly IConfigurationManager _cfg = default!;

    private int _selectedSlot = -1;
    private ProfileSelectorButton? _selectedButton = null;
    private int SlotCount => ListEntries.ChildCount;

    public CharacterSlotSelectorWidget()
    {
        RobustXamlLoader.Load(this);
        Orientation = LayoutOrientation.Vertical;
        _cfg.OnValueChanged(CCVars.GameMaxCharacterSlots, OnValueChanged, true);
    }

    private void OnValueChanged(int newMaxCharacters)
    {
        if (SlotCount > newMaxCharacters)
        {
            for (var i = 0; i < SlotCount - newMaxCharacters; i++)
            {
                ((ProfileSelectorButton)ListEntries.GetChild(SlotCount - 1)).OnPressed -= OnSlotSelected;
                ListEntries.RemoveChild(SlotCount - 1);
            }
            return;
        }

        for (var i = 0; i < newMaxCharacters - SlotCount; i++)
        {
            var newSelector = new ProfileSelectorButton { Slot = SlotCount };
            ListEntries.AddChild(newSelector);
            newSelector.OnPressed += OnSlotSelected;
        }

        if (_selectedButton == null && SlotCount > 0)
            SelectSlot(0);
    }

    private void OnSlotSelected(BaseButton.ButtonEventArgs args)
    {
        var selector = (ProfileSelectorButton) args.Button;
        SelectSlot(selector);
    }

    public void SelectSlot(int slot)
    {
        if (_selectedSlot == slot
            || SlotCount <= slot
            || ListEntries.GetChild(slot) is not ProfileSelectorButton button)
            return;
        SelectSlot(button);
    }

    private void SelectSlot(ProfileSelectorButton slotButton)
    {
        if (_selectedButton == slotButton)
            return;
        if (_selectedButton != null)
        {
            _selectedButton.Pressed = false;
            _selectedButton.Disabled = false;
            _selectedButton.ToggleAllowDelete(true);
        }
        slotButton.ToggleAllowDelete(false);
        _selectedButton = slotButton;
        _selectedButton.Pressed = true;
        _selectedButton.Disabled = true;
        _selectedSlot = slotButton.Slot;
        RaiseGlobalUIEvent(new CharacterProfileSelectedUIEvent(_selectedButton.Slot));
    }

    protected override void EnteredTree()
    {
        SubscribeGlobalUIEvent<CharacterProfileUpdatedUIEvent>(OnSavedCharacterUpdated);
    }

    private void OnSavedCharacterUpdated(CharacterProfileUpdatedUIEvent ev)
    {
        if (SlotCount <= ev.Slot)
        {
            Log.Warning("Tried to update CharacterProfile whose slot was out of range");
            return;
        }
        if (GetChild(ev.Slot) is not ProfileSelectorButton button)
            return;
        button.SetFromProfile(ev.CharacterProfile, ev.PreviewJob);
    }
}