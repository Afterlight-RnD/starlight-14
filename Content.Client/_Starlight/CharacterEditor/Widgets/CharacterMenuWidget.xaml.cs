using Content.Client._Starlight.CharacterEditor.Systems;
using Content.Client._Starlight.UI;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Starlight.CharacterEditor.Widgets;

[GenerateTypedNameReferences]
public sealed partial class CharacterMenuWidget : SLWidget
{
    public CharacterMenuWidget()
    {
        RobustXamlLoader.Load(this);
        CreateCharacter.OnPressed += OnCreateCharacterPressed;
        SelectCharacter.ToggleMode = true;
        SaveChanges.OnPressed += OnSaveChangesPressed;
        DiscardChanges.OnPressed += OnDiscardPressed;
    }

    private void OnDiscardPressed(BaseButton.ButtonEventArgs obj)
    {
        RaiseUIEvent(new DiscardCharacterProfileChangesUIEvent());
        SaveChanges.Disabled = true;
    }

    private void OnSaveChangesPressed(BaseButton.ButtonEventArgs obj)
    {
        SaveChanges.Disabled = true;
        RaiseUIEvent(new SaveCharacterProfileChangesUIEvent());
    }

    protected override void EnteredTree()
    {
        SubscribeUIEvent<CharacterEditorProfileDirtiedUIEvent>(OnCharacterDirtied);
        SubscribeUIEvent<ApplyCharacterProfileChangesUIEvent>(OnCharacterApplied);
    }

    private void OnCharacterApplied(ref readonly ApplyCharacterProfileChangesUIEvent args)
    {
        SaveChanges.Disabled = true;
    }

    private void OnCharacterDirtied(ref readonly CharacterEditorProfileDirtiedUIEvent ev)
    {
        SaveChanges.Disabled = false;
    }

    private void OnCreateCharacterPressed(BaseButton.ButtonEventArgs obj)
    {
        RaiseUIEvent(new CharacterEditorCreateProfileUIEvent());
    }
}