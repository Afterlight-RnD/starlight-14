using Content.Client._Starlight.ProfileEditor.UI;
using Content.Client._Starlight.UI;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
namespace Content.Client._Starlight.CharacterEditor;

public enum CharacterEditorPanelPosition
{
    Main,
    Side
}


[GenerateTypedNameReferences]
public sealed partial class CharacterEditorMainControl : ProfileEditorMainControl<CharacterEditorMainControl, CharacterEditor,CharacterEditorPanelPosition>
{
    protected override Control StepSelectorRoot => EditorStepSelector;

    public override void InjectPanel(CharacterEditorPanelPosition panelEnum, SLControl panel)
    {
        switch (panelEnum)
        {
            case CharacterEditorPanelPosition.Main:
                MainPanel.AddChild(panel);
                break;
            case CharacterEditorPanelPosition.Side:
                SidePanel.AddChild(panel);
                break;
            default:
                throw new ArgumentOutOfRangeException(nameof(panelEnum), panelEnum, null);
        }
    }
}