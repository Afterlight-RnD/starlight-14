using Content.Shared.Preferences;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Starlight.CharacterUIView.UI.Controls;

[GenerateTypedNameReferences]
public sealed partial class SLCharacterView : SpriteView
{
    [Dependency] private readonly IEntityManager _entityManager = default!;
    private CharacterUIViewSystem _characterViewSystem = default!;

    private EntityUid? _viewEntity = null;
    public SLCharacterView()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _characterViewSystem = _entityManager.System<CharacterUIViewSystem>();
    }

    public bool SetCharacter(HumanoidCharacterProfile characterProfile)
    {
        if (_viewEntity != null)
            return _characterViewSystem.UpdateBaseView((_viewEntity.Value, null, null), characterProfile);
        _viewEntity = _characterViewSystem.CreateBaseView(characterProfile);
        return true;
    }

    protected override void ExitedTree()
    {
        if (_viewEntity != null)
            _characterViewSystem.RemoveView(_viewEntity.Value);
    }
}